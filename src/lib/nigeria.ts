// Accepts 0803 000 0000, +234 803 000 0000 and similar; returns +234 format or null.
export function normalisePhone(input: string) {
  const digits = input.replace(/[\s()-]/g, "");
  const match = digits.match(/^(?:\+?234|0)([789][01]\d{8})$/);
  return match ? `+234${match[1]}` : null;
}
